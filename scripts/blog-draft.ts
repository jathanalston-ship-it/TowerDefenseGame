// AUTO DEV-BLOG DRAFTS (docs/WEBSITE.md §blog) — every 10 commits, produce a draft post.
//   npm run blog:draft
// Reads site/blog-state.json (the last drafted commit), and if ≥10 new commits have landed,
// writes site/drafts/DRAFT-<date>.md: the window's changes grouped by category with a
// commentary skeleton. A human polishes it into a BlogPost in site/blog.ts (light review by
// design — the summary does the heavy lifting), then `npm run site` publishes it.

import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const STATE = 'site/blog-state.json';
const EVERY = 10; // draft cadence, in commits

const head = execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim();
const state = existsSync(STATE) ? (JSON.parse(readFileSync(STATE, 'utf8')) as { lastDraftedCommit: string }) : { lastDraftedCommit: '' };

let range = '';
if (state.lastDraftedCommit) {
  try {
    execSync(`git cat-file -e ${state.lastDraftedCommit}`, { stdio: 'ignore' });
    range = `${state.lastDraftedCommit}..HEAD`;
  } catch {
    range = `-n ${EVERY * 2}`; // marker unreachable (rebase) — draft from a recent window
  }
} else {
  range = `-n ${EVERY}`;
}

const log = execSync(`git log --date=short --pretty=format:%ad%s ${range}`, { encoding: 'utf8' }).trim();
const commits = log ? log.split('\n').map((l) => { const [d, s] = l.split(''); return { date: d, subject: s }; }) : [];
if (commits.length < EVERY) {
  console.log(`blog-draft: ${commits.length}/${EVERY} commits since the last draft — nothing to do yet.`);
  process.exit(0);
}

const buckets: Record<string, string[]> = {
  'New systems': [], 'New content': [], 'Balance changes': [], 'Visual improvements': [],
  'Audio': [], 'Performance': [], 'Bug fixes': [], 'Everything else': [],
};
for (const c of commits) {
  const s = c.subject;
  const put = (k: keyof typeof buckets): number => buckets[k].push(`- ${s} _(${c.date})_`);
  if (/fix|bug|crash/i.test(s)) put('Bug fixes');
  else if (/perf|optimi|cache|lod/i.test(s)) put('Performance');
  else if (/audio|music|sound|score|hymn/i.test(s)) put('Audio');
  else if (/visual|render|vfx|art|anim|cinematic|battlefield|cosmetic/i.test(s)) put('Visual improvements');
  else if (/balance|nerf|buff|tunab/i.test(s)) put('Balance changes');
  else if (/tower|hero|boss|card|enemy|biome|equipment|expedition/i.test(s)) put('New content');
  else if (/system|framework|overhaul|feat/i.test(s)) put('New systems');
  else put('Everything else');
}

const today = new Date().toISOString().slice(0, 10);
const sections = Object.entries(buckets).filter(([, v]) => v.length > 0)
  .map(([k, v]) => `## ${k}\n\n${v.join('\n')}\n\n> _Commentary: why this matters to players — one paragraph._`)
  .join('\n\n');
const draft = `# DRAFT devlog — ${today} (${commits.length} commits)

> Auto-generated by \`npm run blog:draft\`. Polish into a BlogPost in \`site/blog.ts\`
> (slug/title/category/tags/summary + prose), then run \`npm run site\` to publish.
> Delete this file once published.

${sections}

## Suggested angle

Pick the largest bucket above and lead with the player-visible change; fold the rest into a
"also this window" list. Target 300–600 words, one strong image or clip.
`;

mkdirSync('site/drafts', { recursive: true });
const file = `site/drafts/DRAFT-${today}.md`;
writeFileSync(file, draft);
writeFileSync(STATE, JSON.stringify({ lastDraftedCommit: head }, null, 2) + '\n');
console.log(`blog-draft: ${commits.length} commits summarized → ${file}`);
